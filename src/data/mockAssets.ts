/** Keep the sample day (24 Sep 2026, 09:44) a couple of minutes behind "now". */
function shiftActivity(iso: string) {
  const anchor = new Date('2026-09-24T09:44:00+03:00').getTime()
  return new Date(new Date(iso).getTime() + (Date.now() - anchor)).toISOString()
}

